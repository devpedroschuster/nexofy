-- ============================================================================
-- PROMOÇÃO AUTOMÁTICA — dispara sempre que uma mudança em `presencas` pode
-- ter liberado uma vaga (cancelamento, falta registrada, falta antecipada
-- de matrícula fixa). Mesmo advisory lock de agendar_avulso, pra serializar
-- com um booking concorrente disputando a mesma vaga.
-- ============================================================================
create or replace function public.promover_fila_apos_liberar_vaga()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_estudio_id uuid;
  v_aula_id bigint;
  v_data_aula date;
  v_libera boolean := false;

  v_ocupacao_atual int;
  v_capacidade_max int;
  v_candidato record;
  v_disp jsonb;
  v_dias_atraso int;
  v_tolerancia int;
  v_presenca_id bigint;
  v_iteracoes int := 0;
begin
  if TG_OP = 'DELETE' then
    if OLD.origem in ('avulso', 'lead') and OLD.status in ('agendado', 'presente') then
      v_libera := true;
      v_estudio_id := OLD.estudio_id;
      v_aula_id := OLD.aula_id;
      v_data_aula := OLD.data_aula;
    end if;
  elsif TG_OP = 'UPDATE' then
    if NEW.origem in ('avulso', 'lead')
       and OLD.status in ('agendado', 'presente')
       and NEW.status in ('falta_justificada', 'falta_nao_avisada') then
      v_libera := true;
      v_estudio_id := NEW.estudio_id;
      v_aula_id := NEW.aula_id;
      v_data_aula := NEW.data_aula;
    end if;
  elsif TG_OP = 'INSERT' then
    if NEW.origem = 'fixo' and NEW.status in ('falta_justificada', 'falta_nao_avisada') then
      v_libera := true;
      v_estudio_id := NEW.estudio_id;
      v_aula_id := NEW.aula_id;
      v_data_aula := NEW.data_aula;
    end if;
  end if;

  if not v_libera or v_data_aula < current_date then
    return coalesce(NEW, OLD);
  end if;

  perform pg_advisory_xact_lock(hashtextextended(v_aula_id::text || '|' || v_data_aula::text, 0));

  loop
    v_iteracoes := v_iteracoes + 1;
    exit when v_iteracoes > 50;

    select ocupacao_atual, capacidade_max
    into v_ocupacao_atual, v_capacidade_max
    from public.calcular_ocupacao_turma(v_aula_id, v_data_aula, v_estudio_id);

    exit when v_ocupacao_atual >= v_capacidade_max;

    select * into v_candidato
    from public.lista_espera
    where estudio_id = v_estudio_id
      and aula_id = v_aula_id
      and data_aula = v_data_aula
      and status = 'aguardando'
    order by criado_em asc
    limit 1;

    exit when v_candidato is null;

    select dias_atraso into v_dias_atraso
    from alunos where id = v_candidato.aluno_id and estudio_id = v_estudio_id;

    select dias_tolerancia_inadimplencia into v_tolerancia
    from estudios where id = v_estudio_id;

    if coalesce(v_dias_atraso, 0) > coalesce(v_tolerancia, 5) then
      update public.lista_espera
        set status = 'expirado', motivo_saida = 'inadimplente'
        where id = v_candidato.id;
      continue;
    end if;

    v_disp := public.verificar_disponibilidade_v2(v_aula_id, v_data_aula, v_estudio_id, v_candidato.aluno_id);

    if (v_disp->>'podeAgendarLivremente')::boolean is false then
      update public.lista_espera
        set status = 'expirado', motivo_saida = 'fora_do_plano'
        where id = v_candidato.id;
      continue;
    end if;

    begin
      insert into public.presencas (estudio_id, aluno_id, aula_id, data_aula, origem, status)
      values (v_estudio_id, v_candidato.aluno_id, v_aula_id, v_data_aula, 'avulso', 'agendado')
      returning id into v_presenca_id;

      update public.lista_espera
        set status = 'convertido', promovido_em = now(), presenca_id = v_presenca_id
        where id = v_candidato.id;
    exception
      when unique_violation then
        -- candidato já tinha um agendamento concorrente pra essa turma/data;
        -- bloco aninhado (savepoint próprio) pra não derrubar promoções já
        -- confirmadas em iterações anteriores deste mesmo loop.
        update public.lista_espera
          set status = 'expirado', motivo_saida = 'conflito_de_agendamento'
          where id = v_candidato.id;
    end;
  end loop;

  return coalesce(NEW, OLD);
end;
$function$;

create trigger trg_promover_fila_apos_liberar_vaga
